export function translate(locale: AppLocale, key: MessageKey, values: Values = {}): string {
  const text = (locale === 'en' ? en : zh)[key];
  return text.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}

// Event handlers and browser services read the current setting when they run.
export function getText(key: MessageKey, values?: Values): string {
  return translate(useSettingsStore.getState().settings.locale, key, values);
}
